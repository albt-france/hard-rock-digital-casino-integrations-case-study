"""Compliance alerts and the onboarding tracker, generated from the SIMULATED approval data (no copy-paste).

Three rules, ordered by severity:
  P1  a game has a live date in a state where it is not approved  -> disable it there now, inform Compliance
  P2  a provider's supplier licence in a state expires within 60 days  -> renewal owner and date
  P3  a submission package is incomplete (PAR sheet, rules/paytable, version hash, RG messaging check)
It also writes docs/integration/compliance_tracker.csv: every game x state of the providers being onboarded (N, Q).

Run: python src/compliance_alerts.py [--as-of YYYY-MM-DD]
"""
from __future__ import annotations

import sys

import pandas as pd

from config import AS_OF, INTEG, SIM, STATUS

DOCS = ["par_sheet", "rules_paytable", "version_hash", "rg_messaging_check"]
LABEL = {"par_sheet": "PAR sheet", "rules_paytable": "rules/paytable", "version_hash": "approved version hash",
         "rg_messaging_check": "RG messaging check"}


def load(as_of: pd.Timestamp):
    a = pd.read_csv(SIM / "game_approvals.csv", parse_dates=["lab_submitted", "cert_date", "submitted", "approved", "live_date"])
    lic = pd.read_csv(SIM / "provider_licences.csv", parse_dates=["expiry_date"])
    return a, lic


def alerts(a: pd.DataFrame, lic: pd.DataFrame, as_of: pd.Timestamp) -> pd.DataFrame:
    rows = []
    p1 = a[a.live_date.notna() & (a.status != "approved")]
    for r in p1.itertuples():
        rows.append(("P1", "Live without approval", r.game_id, r.state,
                     f"live since {r.live_date.date()}, approval status '{r.status}' (submitted {r.submitted.date()})",
                     "Disable the game in this state today (kill switch), confirm with Compliance, report as required"))
    p2 = lic[(lic.licence_status == "active") & (lic.expiry_date <= as_of + pd.Timedelta(days=60))]
    for r in p2.itertuples():
        rows.append(("P2", "Supplier licence expiring", f"Provider {r.provider_id}", r.state,
                     f"expires {r.expiry_date.date()} ({(r.expiry_date - as_of).days} days)",
                     "Confirm renewal filing with the provider; plan disablement if not renewed in time"))
    open_ = a[a.status.isin(["pending", "not_submitted"]) & (a.provider_id != "Q")]
    p3 = open_[~open_[DOCS].all(axis=1)]
    for r in p3.itertuples():
        missing = ", ".join(LABEL[c] for c in DOCS if not getattr(r, c))
        rows.append(("P3", "Missing documents", r.game_id, r.state, f"missing: {missing}",
                     "Request from provider; submission cannot go out until complete"))
    return pd.DataFrame(rows, columns=["severity", "rule", "entity", "state", "detail", "action"])


def tracker(a: pd.DataFrame) -> pd.DataFrame:
    t = a[a.provider_id.isin(["N", "Q"])].copy()
    t["documents_complete"] = t[DOCS].all(axis=1)
    t["certification_status"] = t.cert_date.notna().map({True: "certified", False: "not yet submitted to lab"})
    t.loc[t.lab_submitted.notna() & t.cert_date.isna(), "certification_status"] = "at lab"
    t["next_step"] = "Await provider documents"
    t.loc[t.documents_complete & t.cert_date.isna(), "next_step"] = "Submit to lab"
    t.loc[t.cert_date.notna() & (t.status == "not_submitted"), "next_step"] = "Complete package, submit to state"
    t.loc[t.status == "pending", "next_step"] = "Follow up with state reviewer"
    t.loc[t.status == "approved", "next_step"] = "Schedule launch"
    t.loc[t.status == "not_licensed", "next_step"] = "Blocked: supplier licence pending"
    cols = ["game_id", "provider_id", "state", "lab", "lab_submitted", "cert_date", "cert_ref", *DOCS, "documents_complete",
            "certification_status", "submitted", "status", "approved", "live_date", "next_step"]
    return t[cols].rename(columns={"status": "approval_status"})


def main():
    as_of = pd.Timestamp(sys.argv[sys.argv.index("--as-of") + 1]) if "--as-of" in sys.argv else pd.Timestamp(AS_OF)
    a, lic = load(as_of)
    al = alerts(a, lic, as_of)
    STATUS.mkdir(parents=True, exist_ok=True)
    tracker(a).to_csv(INTEG / "compliance_tracker.csv", index=False, date_format="%Y-%m-%d")
    lines = [f"# Compliance alerts, {as_of.date()}", "",
             "*SIMULATED data (fictional providers and states). Generated by `src/compliance_alerts.py`; "
             "decisions stay with the Compliance team.*", "",
             f"**{(al.severity == 'P1').sum()} P1 · {(al.severity == 'P2').sum()} P2 · {(al.severity == 'P3').sum()} P3**", "",
             "| Severity | Rule | Entity | State | Detail | Action |", "|---|---|---|---|---|---|"]
    lines += [f"| {r.severity} | {r.rule} | {r.entity} | {r.state} | {r.detail} | {r.action} |" for r in al.itertuples()]
    (STATUS / "compliance_alerts.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    al.to_csv(STATUS / "compliance_alerts.csv", index=False)
    print(f"compliance alerts: {len(al)} ({(al.severity == 'P1').sum()} P1) -> docs/status/compliance_alerts.md; "
          f"tracker -> docs/integration/compliance_tracker.csv")


if __name__ == "__main__":
    main()
