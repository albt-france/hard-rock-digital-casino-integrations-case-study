"""Weekly integration status report in Markdown, generated from the pipeline, the approvals, the alerts and the
forecasts (SIMULATED data). Replaces the manual copy-paste into a status deck: run it every Friday.

Sections: headline, what moved this week, what is blocked, risks, forecast launch dates (P50 / P80), post-launch health.
Run: python src/weekly_status.py [--as-of YYYY-MM-DD]   (needs src/run_sql.py and the notebook outputs)
"""
from __future__ import annotations

import json
import sys

import pandas as pd

from config import AS_OF, OUT, SIM, STATUS


def main():
    as_of = pd.Timestamp(sys.argv[sys.argv.index("--as-of") + 1]) if "--as-of" in sys.argv else pd.Timestamp(AS_OF)
    wk0 = as_of - pd.Timedelta(days=6)
    pipe = pd.read_csv(SIM / "integration_pipeline.csv", parse_dates=["start_date", "end_date", "planned_end_date"])
    ap = pd.read_csv(SIM / "game_approvals.csv", parse_dates=["submitted", "approved", "cert_date"])
    fc = pd.read_csv(OUT / "nb_forecast.csv")
    R = json.loads((OUT / "nb_results.json").read_text(encoding="utf-8"))
    al = pd.read_csv(STATUS / "compliance_alerts.csv") if (STATUS / "compliance_alerts.csv").exists() else pd.DataFrame()
    open_ = pipe[pipe.status != "done"]
    blocked = open_[open_.status == "blocked"]
    moved = pipe[pipe.end_date.between(wk0, as_of)]
    appr_wk = ap[ap.approved.between(wk0, as_of)]
    cert_wk = ap[ap.cert_date.between(wk0, as_of)].game_id.nunique()

    L = [f"# Casino integrations: weekly status, week ending {as_of.date()}", "",
         "*SIMULATED data (fictional providers and states). Generated by `src/weekly_status.py` from the pipeline, the "
         "approval tracker and the monitoring outputs.*", "",
         "## Headline",
         f"- **{open_.project_id.nunique()} integrations open**, {len(blocked)} item(s) blocked; "
         f"{(al.severity == 'P1').sum() if len(al) else 0} P1 compliance alert(s) to clear today.",
         f"- **Provider N** is approved in States A and B but waits for State C (open {(as_of - blocked[blocked.project_id == 'N-AGG'].start_date.min()).days} days). "
         "Recommendation: launch A and B now, add C when approved.",
         f"- **Provider Q** forecast launch (States A + B): P50 {R['forecast']['q_ab_p50']}, P80 {R['forecast']['q_ab_p80']} "
         "(commit the P80 date externally).", "",
         "## What moved this week"]
    L += [f"- {r.project_id}: {r.stage}{' (' + r.state + ')' if isinstance(r.state, str) else ''} done on {r.end_date.date()}"
          for r in moved.itertuples()] or ["- No pipeline stage closed this week."]
    L += [f"- {len(appr_wk)} game approvals received ({', '.join(f'{k}: {v}' for k, v in appr_wk.state.value_counts().sort_index().items()) or 'none'}); "
          f"{cert_wk} game(s) certified by the lab.", "", "## Blocked", "",
          "| Project | Stage | State | Open since | Days | Blocker | Next action |", "|---|---|---|---|---|---|---|"]
    nxt = {"Reviewer backlog": "Escalate through Compliance; ask for an expected review date",
           "Currency/decimal mismatch on credits": "Provider fix + regression run on staging (wallet credit cases)"}
    for r in blocked.itertuples():
        L.append(f"| {r.project_id} | {r.stage} | {r.state if isinstance(r.state, str) else '-'} | {r.start_date.date()} | "
                 f"{(as_of - r.start_date).days} | {r.blocker} | {nxt.get(r.blocker, 'Owner to confirm next step')} |")
    soon = open_[open_.planned_end_date.between(as_of, as_of + pd.Timedelta(days=14))]
    L += ["", "## Coming up (next 14 days)"]
    L += [f"- {r.project_id}: {r.stage}{' (' + r.state + ')' if isinstance(r.state, str) else ''} planned to finish "
          f"{r.planned_end_date.date()}" for r in soon.itertuples()] or ["- No planned stage end in the next 14 days."]
    L += ["- Provider N: go / no-go for States A + B launch (approved since July).",
          "- Provider L: confirm the three State B games are disabled (P1) and the approval follow-up is logged."]
    L += ["", "## Risks",
          f"- **State C approvals take {R['cert']['ratio_c']:.1f}x longer** (median {R['cert']['median_by_state']['State C']:.0f} days vs "
          f"{R['cert']['median_by_state']['State A']:.0f}-{R['cert']['median_by_state']['State B']:.0f}); {R['cert']['pending_c']} game approvals pending there. "
          f"Planning a launch on all three states together costs ~{R['forecast']['agg_abc_p50'] - R['forecast']['agg_ab_p50']:.0f} days at P50.",
          f"- **Rollback failures** seen on Provider K (Aggregator Y) on {R['rollback']['days']} days in Jul-Aug: keep the reconciliation "
          "check in Provider Q's acceptance criteria (CI-06, CI-08).",
          f"- **Duplicate catalogue entries** after Provider H's move to direct: {R['dups']['groups']} old aggregator entries still live, "
          f"${R['dups']['fees']:,.0f} of aggregator fees paid since the switch. Switch-off ticket open.", "",
          "## Forecast launch dates (Monte-Carlo, 10,000 runs)", "", "| Provider | State | P50 | P80 |", "|---|---|---|---|"]
    L += [f"| {r.provider} | {r.state} | {r.p50_date} | {r.p80_date} |" for r in fc.itertuples()]
    L += ["", "## Post-launch health (last 90 days of data)",
          f"- RTP monitoring: {len(R['rtp']['escalate'])} game escalated ({', '.join(R['rtp']['escalate'])}: realised "
          f"{R['rtp']['G-012']['real']:.1%} vs {R['rtp']['G-012']['theo']:.1%} certified, z = {R['rtp']['G-012']['z']:.1f}); "
          f"{len(R['rtp']['watch'])} on watch; C-007's {R['rtp']['C-007']['real']:.1%} is within its variance band (no action).",
          f"- Launch errors: last incident Provider F, {R['launch']['first']} to {R['launch']['last']} "
          f"(peak {R['launch']['peak_rate']:.0%}, ~${R['launch']['ggr_lost']:,.0f} GGR lost).", ""]
    STATUS.mkdir(parents=True, exist_ok=True)
    out = STATUS / f"weekly_status_{as_of.date()}.md"
    out.write_text("\n".join(L), encoding="utf-8")
    print("weekly status ->", out.relative_to(STATUS.parents[1]))


if __name__ == "__main__":
    main()
